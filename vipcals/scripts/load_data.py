    uvsrt.inseq = data.seq
    uvsrt.outname = data.name
    uvsrt.outclass = data.klass
    uvsrt.outdisk = data.disk
    uvsrt.outseq = data.seq
    
    uvsrt.sort = 'TB'
            
    uvsrt.go()